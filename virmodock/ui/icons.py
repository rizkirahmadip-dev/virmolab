_cache = {}


def svg(nama, warna="#465263", lebar=1.6):
    isi = PATH.get(nama, "")
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{warna}" '
            f'stroke-width="{lebar}" stroke-linecap="round" stroke-linejoin="round" color="{warna}">'
            + isi.replace('currentColor', warna) + '</svg>')


def pixmap(nama, warna, ukuran=16, skala=2.0):
    n = int(ukuran * skala)
    pm = QPixmap(n, n)
    pm.fill(Qt.transparent)
    r = QSvgRenderer(QByteArray(svg(nama, warna).encode()))
    p = QPainter(pm)
    r.render(p)
    p.end()
    pm.setDevicePixelRatio(skala)
    return pm


def ikon(nama, warna, warna_aktif=None, ukuran=16):
    k = (nama, warna, warna_aktif, ukuran)
    if k in _cache:
        return _cache[k]
    ic = QIcon()
    ic.addPixmap(pixmap(nama, warna, ukuran), QIcon.Normal, QIcon.Off)
    if warna_aktif:
        ic.addPixmap(pixmap(nama, warna_aktif, ukuran), QIcon.Normal, QIcon.On)
    _cache[k] = ic
    return ic


def ikon_nomor(n, warna, ukuran=18):
    """Lingkaran bergaris dengan angka di tengah (status langkah yang belum selesai)."""
    k = ("nomor", n, warna, ukuran)
    if k in _cache:
        return _cache[k]
    teks = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><circle cx="12" cy="12" r="10" '
            f'fill="none" stroke="{warna}" stroke-width="1.6"/><text x="12" y="16.2" text-anchor="middle" '
            f'font-family="Segoe UI, Arial" font-size="12" font-weight="600" fill="{warna}">{n}</text></svg>')
    skala = 2.0
    s = int(ukuran * skala)
    pm = QPixmap(s, s)
    pm.fill(Qt.transparent)
    p = QPainter(pm)
    QSvgRenderer(QByteArray(teks.encode())).render(p)
    p.end()
    pm.setDevicePixelRatio(skala)
    _cache[k] = QIcon(pm)
    return _cache[k]
